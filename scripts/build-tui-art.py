"""Turn the generated mascot PNGs into the data module the plugins import."""

from __future__ import annotations

import base64
import json
import sys
from pathlib import Path

STATES = [
    "idle",
    "thinking",
    "reading",
    "coding",
    "running",
    "browsing",
    "happy",
    "sad",
    "sleeping",
]

MASCOTS = [
    {
        "id": "empo",
        "name": "Empo",
        "tagline": "The glowing compass-star",
        "accent": "#ff9ecf",
    },
    {
        "id": "clawd",
        "name": "Clawd",
        "tagline": "The Claude Code crab",
        "accent": "#d77856",
    },
]


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: build-tui-art.py <png-dir> <out.ts>", file=sys.stderr)
        return 1

    png_dir = Path(sys.argv[1])
    out_path = Path(sys.argv[2])

    frames: dict[str, dict[str, str]] = {}
    for mascot in MASCOTS:
        frames[mascot["id"]] = {}
        for state in STATES:
            png = png_dir / f"{mascot['id']}-{state}.png"
            if not png.is_file():
                print(f"missing frame: {png}", file=sys.stderr)
                return 1
            encoded = base64.b64encode(png.read_bytes()).decode("ascii")
            frames[mascot["id"]][state] = f"data:image/png;base64,{encoded}"

    lines = [
        "// SPDX-License-Identifier: GPL-3.0-only",
        "// Copyright (C) 2026 Softbrick (zcyrl)",
        "// Generated by scripts/generate-tui-assets.sh. Do not edit by hand.",
        "",
        "export const MASCOT_STATES = " + json.dumps(STATES) + " as const",
        "export type MascotState = (typeof MASCOT_STATES)[number]",
        "",
        "export type MascotId = \"empo\" | \"clawd\"",
        "",
        "export interface MascotInfo {",
        "  readonly id: MascotId",
        "  readonly name: string",
        "  readonly tagline: string",
        "  readonly accent: string",
        "}",
        "",
        "export const MASCOTS: readonly MascotInfo[] = " + json.dumps(MASCOTS, indent=2),
        "",
        "export const MASCOT_FRAMES: Record<MascotId, Record<MascotState, string>> = {",
    ]

    for mascot in MASCOTS:
        lines.append(f'  {mascot["id"]}: {{')
        for state in STATES:
            lines.append(f'    {state}: "{frames[mascot["id"]][state]}",')
        lines.append("  },")
    lines.append("}")
    lines.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(out_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
